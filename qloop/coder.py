class LexiconCoder:
    name = "lexicon"

    def code(self, texts: list[str]) -> list[list[str]]:
        out = []
        for t in texts:
            out.append([th for th, kws in THEMES.items() if any(k in t for k in kws)])
        return out


def theme_shares(coded: list[list[str]]) -> dict[str, float]:
    n = max(len(coded), 1)
    cnt: dict[str, int] = {}
    for labels in coded:
        for th in set(labels):
            cnt[th] = cnt.get(th, 0) + 1
    return {k: v / n for k, v in sorted(cnt.items(), key=lambda kv: -kv[1])}
